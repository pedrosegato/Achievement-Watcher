import { invoke } from "@tauri-apps/api/core";
import type {
  CloudGameView,
  CloudOverview,
  Diagnostics,
  FfmpegStatus,
  GameDetail,
  GameRow,
  LaunchChoice,
  Locale,
  LocaleInfo,
  PlayResponse,
  PlayState,
  PresetInfo,
  PreviewKind,
  Settings,
  SoundEvent,
  SoundPack,
  UpdateStatus,
  UserFolder,
} from "../types/domain";

const COMMANDS = {
  listGames: "list_games",
  gameDetail: "game_detail",
  getSettings: "get_settings",
  saveSettings: "save_settings",
  listPresets: "list_presets",
  previewPreset: "preview_preset",
  listSounds: "list_sounds",
  previewSound: "preview_sound",
  openUserFolder: "open_user_folder",
  testNotification: "test_notification",
  rescan: "rescan",
  diagnostics: "diagnostics",
  exportDiagnostics: "export_diagnostics",
  exportGameReport: "export_game_report",
  openPath: "open_path",
  overlayGame: "overlay_game",
  hotkeyError: "hotkey_error",
  toggleOverlay: "toggle_overlay",
  ffmpegStatus: "ffmpeg_status",
  downloadFfmpeg: "download_ffmpeg",
  cancelFfmpeg: "cancel_ffmpeg",
  updateStatus: "update_status",
  checkUpdate: "check_update",
  installUpdate: "install_update",
  uiLocale: "ui_locale",
  supportedLocales: "supported_locales",
  cloudOverview: "cloud_overview",
  setCloudFolder: "set_cloud_folder",
  setDeviceName: "set_device_name",
  cloudGame: "cloud_game",
  setGameSync: "set_game_sync",
  setGameSavePath: "set_game_save_path",
  cloudUndo: "cloud_undo",
  cloudSetPrincipal: "cloud_set_principal",
  cloudSyncNow: "cloud_sync_now",
  playState: "play_state",
  playGame: "play_game",
  playAnyway: "play_anyway",
  cancelPlay: "cancel_play",
  stopGame: "stop_game",
  setLaunchExe: "set_launch_exe",
  launchChoice: "launch_choice",
} as const;

export const api = {
  listGames: () => invoke<GameRow[]>(COMMANDS.listGames),
  gameDetail: (appId: number) => invoke<GameDetail>(COMMANDS.gameDetail, { appId }),
  getSettings: () => invoke<Settings>(COMMANDS.getSettings),
  saveSettings: (settings: Settings) => invoke<Settings>(COMMANDS.saveSettings, { settings }),
  listPresets: () => invoke<PresetInfo[]>(COMMANDS.listPresets),
  previewPreset: (id: string, kind: PreviewKind) =>
    invoke<void>(COMMANDS.previewPreset, { id, kind }),
  listSounds: () => invoke<SoundPack[]>(COMMANDS.listSounds),
  previewSound: (id: string, event: SoundEvent) =>
    invoke<number | null>(COMMANDS.previewSound, { id, event }),
  openUserFolder: (kind: UserFolder) => invoke<void>(COMMANDS.openUserFolder, { kind }),
  testNotification: () => invoke<void>(COMMANDS.testNotification),
  rescan: () => invoke<boolean>(COMMANDS.rescan),
  diagnostics: () => invoke<Diagnostics>(COMMANDS.diagnostics),
  exportDiagnostics: () => invoke<string>(COMMANDS.exportDiagnostics),
  exportGameReport: (appId: number) => invoke<string>(COMMANDS.exportGameReport, { appId }),
  openPath: (path: string) => invoke<void>(COMMANDS.openPath, { path }),
  overlayGame: () => invoke<GameDetail | null>(COMMANDS.overlayGame),
  hotkeyError: () => invoke<string | null>(COMMANDS.hotkeyError),
  toggleOverlay: () => invoke<void>(COMMANDS.toggleOverlay),
  ffmpegStatus: () => invoke<FfmpegStatus>(COMMANDS.ffmpegStatus),
  downloadFfmpeg: () => invoke<void>(COMMANDS.downloadFfmpeg),
  cancelFfmpeg: () => invoke<void>(COMMANDS.cancelFfmpeg),
  updateStatus: () => invoke<UpdateStatus>(COMMANDS.updateStatus),
  checkUpdate: () => invoke<void>(COMMANDS.checkUpdate),
  installUpdate: () => invoke<void>(COMMANDS.installUpdate),
  uiLocale: () => invoke<Locale>(COMMANDS.uiLocale),
  supportedLocales: () => invoke<LocaleInfo[]>(COMMANDS.supportedLocales),
  cloudOverview: () => invoke<CloudOverview>(COMMANDS.cloudOverview),
  setCloudFolder: (path: string | null) => invoke<void>(COMMANDS.setCloudFolder, { path }),
  setDeviceName: (name: string) => invoke<void>(COMMANDS.setDeviceName, { name }),
  cloudGame: (appId: number) => invoke<CloudGameView>(COMMANDS.cloudGame, { appId }),
  setGameSync: (appId: number, enabled: boolean) =>
    invoke<void>(COMMANDS.setGameSync, { appId, enabled }),
  setGameSavePath: (appId: number, path: string | null) =>
    invoke<void>(COMMANDS.setGameSavePath, { appId, path }),
  cloudUndo: (appId: number) => invoke<void>(COMMANDS.cloudUndo, { appId }),
  cloudSyncNow: (appId: number) => invoke<void>(COMMANDS.cloudSyncNow, { appId }),
  cloudSetPrincipal: (appId: number, snapshotId: string) =>
    invoke<void>(COMMANDS.cloudSetPrincipal, { appId, snapshotId }),
  playState: (appId: number) => invoke<PlayState>(COMMANDS.playState, { appId }),
  playGame: (appId: number, confirmedElsewhere: boolean) =>
    invoke<PlayResponse>(COMMANDS.playGame, { appId, confirmedElsewhere }),
  playAnyway: (appId: number) => invoke<void>(COMMANDS.playAnyway, { appId }),
  cancelPlay: (appId: number) => invoke<void>(COMMANDS.cancelPlay, { appId }),
  stopGame: (appId: number) => invoke<void>(COMMANDS.stopGame, { appId }),
  setLaunchExe: (appId: number, path: string | null) =>
    invoke<void>(COMMANDS.setLaunchExe, { appId, path }),
  launchChoice: (appId: number) => invoke<LaunchChoice>(COMMANDS.launchChoice, { appId }),
};

export function errorMessage(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}
